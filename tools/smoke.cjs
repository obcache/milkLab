const { _electron: electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');

(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'milklab-smoke-'));
  const env = { ...process.env, MILKLAB_USER_DATA: path.join(temp, 'state'), MILKLAB_STORAGE_ROOT: path.join(temp, 'library') };
  delete env.ELECTRON_RUN_AS_NODE;
  const errors = [];
  const drag = async (source, target) => {
    const dataTransfer = await window.evaluateHandle(() => new DataTransfer());
    await source.dispatchEvent('dragstart', { dataTransfer });
    await target.dispatchEvent('dragenter', { dataTransfer });
    await target.dispatchEvent('dragover', { dataTransfer });
    await target.dispatchEvent('drop', { dataTransfer });
    await source.dispatchEvent('dragend', { dataTransfer });
    await dataTransfer.dispose();
  };
  const launch = () => electron.launch({ ...(process.argv.includes('--packaged') ? { executablePath: path.resolve('dist/win-unpacked/milkLab.exe'), args: [] } : { args: [path.resolve('build/electron/main.cjs')] }), env, timeout: 30000 });
  let application = await launch();
  let window = await application.firstWindow();
  window.on('pageerror', e => errors.push(e.message));
  window.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  try {
    await window.getByRole('tab', { name: 'Spectral drift.milk' }).waitFor({ timeout: 30000 });
    await window.getByText('projectM · WebGL2', { exact: true }).waitFor({ timeout: 30000 });
    assert.equal(await window.locator('vite-error-overlay').count(), 0);
    assert.match(await window.title(), /milkLab/);
    const library = window.getByRole('listbox', { name: 'Managed preset library' });
    const entries = () => window.getByRole('listbox', { name: 'Playlist entries' }).getByRole('option');
    await library.getByRole('option').filter({ hasText: 'Orbit study.milk' }).dblclick();
    await window.getByRole('tab', { name: 'Orbit study.milk' }).waitFor();
    await window.getByRole('button', { name: 'Add to playlist', exact: true }).click();
    await entries().first().waitFor();
    await drag(library.getByRole('option').filter({ hasText: 'Spectral drift.milk' }), window.locator('.playlist-list'));
    await window.waitForFunction(() => document.querySelectorAll('.playlist-row').length === 2);
    await drag(entries().nth(1), entries().first());
    assert.match(await entries().first().innerText(), /Spectral drift/);
    await drag(window.getByRole('button', { name: /^Spiral drift/ }), window.getByRole('textbox', { name: 'Preset code editor' }));
    await window.getByLabel('Unsaved changes').first().waitFor();
    await window.waitForTimeout(600);
    let record = JSON.parse(await fs.readFile(path.join(temp, 'state/workspace.json'), 'utf8'));
    const orbit = record.documents.find(d => d.name === 'Orbit study.milk');
    let draft = await fs.readFile(path.join(temp, `state/drafts/${orbit.id}.milk`), 'utf8');
    assert.match(draft, /Spiral drift/);
    const max = Math.max(...[...draft.matchAll(/per_frame_(\d+)=/g)].map(m => Number(m[1])));
    const editor = window.getByRole('textbox', { name: 'Preset code editor' });
    await editor.press('Control+End');
    await window.keyboard.insertText(`\nper_frame_${max + 1}=zoom=sin(;`);
    await window.locator('.diagnostic-row.error').first().waitFor();
    await window.locator('.cm-lintRange-error').first().waitFor({ timeout: 5000 });
    await editor.press('Control+z');
    await window.getByText('No problems detected in the active preset.', { exact: true }).waitFor();
    await editor.press('Control+End'); await window.keyboard.insertText(`\nper_frame_${max + 1}=zoom=si`); await editor.press('Control+Space');
    await window.locator('.cm-tooltip-autocomplete').waitFor();
    assert.match(await window.locator('.cm-tooltip-autocomplete').innerText(), /sin/);
    await editor.press('Escape'); await editor.press('Control+z');
    await editor.press('Control+s');
    await window.waitForFunction(() => !document.querySelector('.editor-tab.active .unsaved-dot'));
    assert.match(await fs.readFile(orbit.path, 'utf8'), /Spiral drift/);
    await window.getByTitle('Effects panel options', { exact: true }).click();
    await window.getByRole('button', { name: 'Move to left column' }).click();
    assert.equal(await window.locator('.left [data-panel="effects"]').count(), 1);
    await window.getByTitle('Effects panel options', { exact: true }).click(); await window.getByRole('button', { name: 'Move up', exact: true }).click();
    const beforeHeight = (await window.locator('[data-panel="library"]').boundingBox()).height;
    const panelSplit = await window.getByRole('separator', { name: 'Resize Preset library and Effects' }).boundingBox();
    await window.mouse.move(panelSplit.x + 20, panelSplit.y + 2); await window.mouse.down(); await window.mouse.move(panelSplit.x + 20, panelSplit.y + 30); await window.mouse.up();
    assert(Math.abs((await window.locator('[data-panel="library"]').boundingBox()).height - beforeHeight) > 5);
    const split = await window.getByRole('separator', { name: 'Resize left column', exact: true }).boundingBox();
    await window.mouse.move(split.x + 2, split.y + 100); await window.mouse.down(); await window.mouse.move(split.x + 32, split.y + 100); await window.mouse.up();
    await window.getByRole('button', { name: 'Effects', exact: true }).click();
    assert(await window.locator('[data-panel="effects"]').evaluate(el => el.classList.contains('collapsed')));
    await window.getByRole('button', { name: 'File', exact: true }).click(); await window.getByRole('button', { name: /^Settings…/ }).click();
    await window.getByLabel('Editor font size').fill('14'); await window.getByRole('button', { name: 'Save settings', exact: true }).click();
    await window.getByRole('dialog').waitFor({ state: 'hidden' });
    const valid = path.join(temp, 'Repaired shader.milk'), invalid = path.join(temp, 'Invalid.milk');
    await fs.writeFile(valid, 'MILKDROP_PRESET_VERSION=201\nPSVERSION=2\nPSVERSION_WARP=0\nPSVERSION_COMP=2\n[preset00]\nfDecay=0.98\ncomp_1=`shader_body\ncomp_2=`{\ncomp_3=`float aspect=aspect.x/aspect.y;\ncomp_4=`ret=0.5+0.5*tanh(float3(uv.x,uv.y,aspect));\ncomp_5=`}\n');
    await fs.writeFile(invalid, 'this is not a preset');
    await application.evaluate(({ dialog }, paths) => { globalThis.__originalOpen = dialog.showOpenDialog; dialog.showOpenDialog = async () => ({ canceled: false, filePaths: paths }); }, [valid, invalid]);
    await window.getByRole('button', { name: 'Import presets…', exact: true }).click();
    await window.getByRole('heading', { name: 'Preset import report' }).waitFor();
    assert.match(await window.getByRole('dialog').innerText(), /1 presets accepted · 1 rejected/);
    assert.match(await window.getByRole('dialog').innerText(), /renamed local shader variable aspect/);
    assert.match(await window.getByRole('dialog').innerText(), /scalar\/vector/);
    await window.getByRole('button', { name: 'Done', exact: true }).click();
    await application.evaluate(({ dialog }) => { dialog.showOpenDialog = globalThis.__originalOpen; });
    await library.getByRole('option').filter({ hasText: 'Repaired shader.milk' }).dblclick();
    await window.getByText('projectM · WebGL2', { exact: true }).waitFor(); await window.waitForTimeout(1500);
    assert.equal(await window.locator('.diagnostic-row.error').count(), 0, await window.locator('body').innerText());
    await window.keyboard.press('Control+n');
    const recoveryEditor = window.getByRole('textbox', { name: 'Preset code editor' });
    await recoveryEditor.press('Control+End'); await window.keyboard.insertText('\n// crash recovery sentinel\n');
    await window.waitForTimeout(800);
    record = JSON.parse(await fs.readFile(path.join(temp, 'state/workspace.json'), 'utf8'));
    const recoveryDoc = record.documents.find(d => d.id === record.activeId);
    assert(recoveryDoc.dirty); assert.equal(recoveryDoc.path, null);
    assert.match(await fs.readFile(path.join(temp, `state/drafts/${recoveryDoc.id}.milk`), 'utf8'), /crash recovery sentinel/);
    const expectedLayout = record.layout;
    await new Promise(resolve => {
      application.process().once('exit', resolve);
      if (process.platform === 'win32') execFileSync('taskkill', ['/PID', String(application.process().pid), '/T', '/F'], { windowsHide: true, stdio: 'pipe' });
      else application.process().kill('SIGKILL');
    });
    await new Promise(resolve => setTimeout(resolve, 700));
    application = await launch(); window = await application.firstWindow();
    window.on('pageerror', e => errors.push(e.message));
    await window.getByRole('tab', { name: recoveryDoc.name }).waitFor();
    await window.getByLabel('Unsaved changes').first().waitFor();
    assert.equal(await window.locator('.left [data-panel="effects"]').count(), 1);
    assert(await window.locator('[data-panel="effects"]').evaluate(el => el.classList.contains('collapsed')));
    const restored = await window.evaluate(() => window.milkLab.bootstrap());
    assert.match(restored.workspace.documents.find(d => d.id === recoveryDoc.id).content, /crash recovery sentinel/);
    assert.deepEqual(restored.workspace.layout, expectedLayout); assert.equal(restored.settings.fontSize, 14);
    const playlistText = await fs.readFile(path.join(temp, 'library/playlists/Studio_session.txt'), 'utf8');
    assert.equal(playlistText.trim().split(/\r?\n/).length, 2); assert(!playlistText.startsWith('['));
    await window.getByRole('button', { name: 'Pause preview', exact: true }).click();
    await window.getByText('Preview paused', { exact: true }).waitFor();
    await window.getByRole('button', { name: 'Play preview', exact: true }).click();
    // Shrink from deliberately wide preferences, not only the default layout.
    const widenLeft = await window.getByRole('separator', { name: 'Resize left column', exact: true }).boundingBox();
    await window.mouse.move(widenLeft.x + 2, widenLeft.y + 80); await window.mouse.down(); await window.mouse.move(widenLeft.x + 240, widenLeft.y + 80); await window.mouse.up();
    const widenRight = await window.getByRole('separator', { name: 'Resize right column', exact: true }).boundingBox();
    await window.mouse.move(widenRight.x + 2, widenRight.y + 80); await window.mouse.down(); await window.mouse.move(widenRight.x - 270, widenRight.y + 80); await window.mouse.up();
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1060, 720));
    await window.waitForTimeout(400);
    const overflow = await window.evaluate(() => document.querySelector('.dock-workspace').scrollWidth > document.querySelector('.dock-workspace').clientWidth);
    assert.equal(overflow, false, 'Workspace must fit the minimum desktop window.');
    await window.screenshot({ path: path.join(temp, 'narrow.png') });
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1600, 1000));
    await window.getByRole('button', { name: 'View', exact: true }).click(); await window.getByRole('button', { name: 'Reset workspace layout', exact: true }).click();
    await window.getByRole('tab', { name: 'Spectral drift.milk' }).click();
    await window.waitForTimeout(900);
    await window.screenshot({ path: path.join(temp, 'workspace.png') });
    console.log(JSON.stringify({ passed: ['app identity and nonblank screen', 'real projectM WebGL2', 'tab opening and explicit save', 'library add and drag', 'playlist reorder and plain text persistence', 'effect drag inserts real code', 'native expression diagnostics and underlines', 'autocomplete', 'panel move/order/collapse/height/width', 'settings persistence', 'normalized import and invalid rejection', 'normalized HLSL renders', 'crash recovery across restart', 'preview play/pause', '1060x720 and 1600x1000 layout'], temp, title: await window.title(), errors }, null, 2));
    assert.equal(errors.length, 0, errors.join('\n'));
  } catch (error) {
    await window.screenshot({ path: path.join(temp, 'failure.png') }).catch(() => {});
    console.error(JSON.stringify({ temp, errors, body: (await window.locator('body').innerText().catch(() => '')).slice(-2000), lint: await window.locator('[class*="lint"]').evaluateAll(elements => elements.map(el => ({ class: el.className, text: el.textContent }))).catch(() => []) }, null, 2));
    throw error;
  } finally { await application.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
